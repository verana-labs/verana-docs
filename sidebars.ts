import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

// Three sidebars, one per navbar entry. Sections are folders; each folder has an
// index.md that serves as the section page. Generated API references are
// imported from the sidebar files the OpenAPI plugin writes.

// The OpenAPI plugin writes this file on `npm run gen-api-docs`; before the first
// generation it does not exist, and the config must still load for that command.
function generatedSidebar(path: string) {
  try {
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    return require(path).default ?? require(path);
  } catch {
    return [];
  }
}
